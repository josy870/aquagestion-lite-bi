-- poza             | 5
-- lote             | 6
-- registro_diario  | ~250+

-- Vista rápida de rango de fechas y temperaturas
SELECT
    MIN(fecha)                      AS fecha_inicio,
    MAX(fecha)                      AS fecha_fin,
    COUNT(*)                        AS total_registros,
    ROUND(AVG(temp_promedio), 2)    AS temp_promedio_global,
    SUM(cantidad_bajas)             AS total_bajas,
    ROUND(SUM(kg_alimento), 2)      AS total_kg_alimento
FROM oltp.registro_diario;
